package com.nudge.app.ui

/**
 * 歌词滚动动画的全部可调参数。
 *
 * 抽成数据类而不是散在 [LyricsOverlay] 里的常量，是为了让 debug 包的
 * 「歌词动画实验室」能在运行时换一整套参数看效果——这些值的好坏只能靠
 * 连着对比试出来，改常数再重编译一轮要一分多钟，试不了几组就没耐心了。
 *
 * **纯 Kotlin，不依赖任何 Android 类**（长度一律用 Float 表示 dp 数值而非
 * `Dp`），与 `GestureRecognizer` 同理：参数之间有若干必须维持的不变式
 * （见各字段注释），要能在 JVM 上单测。
 *
 * release 包里只有 [DEFAULT] 会被用到，实验室调出来的值最终要手写回这里。
 * 刻意不做持久化：这是开发期的取景器，不是给用户的配置项——歌词动画的
 * 好坏没有「因人而异」的成分，把它做成用户可调只会让线上出现一堆没人
 * 能复现的观感问题。
 */
data class LyricsAnimSpec(
    /**
     * 当前行固定在屏幕上的第几行（0 基，0 表示贴着容器顶边）。
     *
     * 早先是恒定居中（容器高度的一半）。改为固定行号是因为居中不符合
     * 阅读的实际重心：人读歌词时注意力在「下一句是什么」，正下方的预读区
     * 比正上方已唱过的行重要得多，把焦点压到偏上的位置才能让预读区更大。
     *
     * 取 3（即视觉上的第 4 行）：上方留三行已唱过的做上下文。
     * 早先取 2 实测仍偏上——预读区是够了，但焦点贴着容器顶边，
     * 上方那点上下文被边缘淡出吃掉大半，看着像「当前行被顶在天花板上」。
     *
     * **这是不带译文时的基准值**，开了译文要用 [anchorRowFor] 取实际锚点。
     */
    val anchorRow: Int = 3,

    /**
     * 缓动曲线「懒惰度」的梯度端点：屏幕**顶部**最干脆、**底部**最懒。
     *
     * 这是整块动画的核心参数，含义是**贝塞尔曲线第一个控制点的 x**
     * （见 `LyricsOverlay.easingFor`）。值越大，起步越慢、后段越赶，
     * 即「被前面的行拖着走」的感觉越强。
     *
     * 方向：列表整体往**上**走，最上面那行是这趟位移里走得最久、
     * 最先该落定的；越靠下的行越是被拖着走，起步越慢。
     * 所以懒惰度沿屏幕**自上而下递增**。
     *
     * **这里不是弹簧，没有过冲**。早先用 `spring(dampingRatio, stiffness)`，
     * 那是 PID 式的模型：快速拉到目标再来回震荡，越软的行震得越厉害。
     * 实际要的是**单调逼近**——永远不越过上一行的位置，只是趋近速度不同。
     * 震荡在盲操场景里尤其糟：焦点行晃一下会被读成「歌词跳了」。
     *
     * 曾经写反过一版（顶懒底干脆），理由是「被拖拽的只能是后面的行」，
     * 这句话没错，但**「后面的行」指的是下方的行**。
     * 更早还有一版用 `abs(index - current)` 取无向距离，梯度以当前行为中心
     * 对称扩散，拖尾在上下两个方向同时出现。
     *
     * 梯度基准用**目标位置**（动画结束后这行落在第几行）而不是实时位置：
     * 后者会让曲线随自身动画状态变化，构成非线性反馈。
     * 目标位置是静态量，每次换行只重算一次。
     *
     * 两端的差要足够大，否则看不出错峰——相邻行的曲线太接近，
     * 肉眼会把整列合成一个刚体，退化成「整列线性滚动」。
     */
    val easeTop: Float = 0.1f,
    val easeBottom: Float = 0.95f,

    /**
     * 懒惰度梯度铺开的行数，从屏幕顶边（第 0 行）往下数。
     *
     * 超出这个跨度的行统一取 [easeBottom]，即最懒档。
     * 那些行还在裁切边界外或边缘淡出区里，再懒也只是「慢慢飘进来」，
     * 不会干扰阅读。
     *
     * 取 7 是为了让跨度大致覆盖可视区：铺得太窄（比如 3）会让梯度在第 3 行
     * 就跑完，往下全是同一档，又退化成「上面几行动、下面一坨一起动」；
     * 铺得太开则相邻行的差太小，链条感反而弱。
     */
    val gradientRampLines: Float = 7f,

    /**
     * 整列位移的时长（毫秒）。**所有行共用**——同时开始、同时结束。
     *
     * 错峰不靠时长差，靠各行不同的缓动曲线（见 [easeTop] / [easeBottom]）：
     * 下面的行起步更慢、后段赶上来，滑动途中行距会先拉开再收拢，
     * 这就是「被拖着走」的观感来源。
     *
     * 让时长也跟着变的话，快歌连续换行时下面的行会追不上，
     * 位移累积起来越滚越偏。同时结束是个硬约束。
     *
     * 420ms 比早先弹簧的落定估算（约 290ms）略长：补间没有弹簧那条
     * 长长的收敛尾巴，同样时长下感觉更快，要补回来一点。
     */
    val settleTweenMs: Int = 420,

    /**
     * 即将进入可视区那一行的**起始延迟**（毫秒）。
     *
     * 整列同速上移之后，错峰全靠这一个参数：可视区内的行立刻一起走，
     * 最下面那行等这么久才起步，再按 [incomingEase] 缓缓吸附上来。
     * 观感是「整列先走，最后一句被拖着跟上来」。
     *
     * 做成**延迟**而不是只给它一条更懒的曲线：曲线再懒也是从第 0ms
     * 就开始动的，肉眼分不出「懒」和「慢」；一个明确的静止段才读得出
     * 「它晚了一拍」。这与 [focusLeadMs] 那里「想改时序要调延迟而不是
     * 时长」是同一条经验。
     *
     * 取 120ms：明显能看出来，又不至于让它在整列都停下后才姗姗来迟
     * （延迟 + [settleTweenMs] 要留在一次换行的间隔内，否则快歌时
     * 它会被下一次换行打断，永远追不上）。
     */
    val incomingDelayMs: Int = 120,

    /**
     * **非当前行统一用这一个模糊半径**，与距离无关。开启后
     * [maxBlurDp] / [blurRampLines] / [blurCutoffLines] 全部不参与。
     *
     * 这是观察 **Android 版 Apple Music** 得出的形态：那里所有非当前行
     * 糊的程度**看不出差别**，没有「随距离渐进加深」的梯度，层次完全
     * 交给透明度。我们早先那套逐行渐进的模型（0.9/1.8/2.7…dp）是推断，
     * 不是照着实物做的。
     *
     * 同时它也是**流畅度的关键**：逐行渐进意味着 17 行有十几种互不相同
     * 的半径，每一种都要独立生成一遍模糊；统一成一档后，所有非当前行
     * 的半径完全相同，Skia 才谈得上复用。
     *
     * 注意这与被否掉的 [blurSteps]（离散成 3 档）**不是一回事**：
     * 3 档仍有 3 种半径，且那版向上取整还把半径抬大了，两头不讨好。
     * 两档才是实物的形态。
     *
     * 设为负数表示回到逐行渐进的旧模型，供实验室对比用。
     */
    val uniformBlurDp: Float = 0f,

    /**
     * 当前行的模糊半径（dp）。
     *
     * 取一个**极小的非零值**而不是 0：Apple Music 的当前行并非纯锐利，
     * 字的边缘带一点柔光。0 也可以接受（少一个离屏缓冲，更省），
     * 实验室里可以对比。
     */
    val currentBlurDp: Float = 0f,

    /**
     * 最远处行的模糊半径（dp）。峰值要守住「最远处仍认得出字」。
     *
     * **仅在 [uniformBlurDp] 为负（回到逐行渐进模型）时生效。**
     */
    val maxBlurDp: Float = 9f,

    /**
     * 模糊达到 [maxBlurDp] 所需的距离（行）。
     *
     * 与 [maxBlurDp] **配着调**：决定观感的是曲线斜率而不只是峰值。
     * 只抬峰值不拉跨度，紧邻当前行的一两行会跟着糊掉，「预读下一句」就没了。
     */
    val blurRampLines: Float = 10f,

    /**
     * 超过这个距离（行）的行**不再挂 blur**，纯性能优化。
     *
     * 每一个挂了 `Modifier.blur` 的行都要开一个**全屏宽的离屏缓冲**，
     * 而渲染窗口有 17 行——真机实测这 17 个缓冲把 `issueDrawCommands`
     * 拖到 6~11ms，96Hz 下预算才 10.4ms，于是 **24.6% 的帧掉帧**，
     * 观感就是「滚动一卡一卡、像帧数不够」。关掉全部 blur 后掉帧率
     * 降到 3.3%、90 分位 30ms→13ms，确认瓶颈就在这里。
     *
     * 取 8 是因为**从 offset=8 起 alpha 已经撞到 [alphaFar] 的地板**
     * （0.55 起、每行降 0.035，第 8 行正好到 0.3），blur 也接近
     * [maxBlurDp] 的封顶。再往远，各行的 alpha 与 blur 都不再变化，
     * 彼此之间**没有任何层次差别**，那里的 blur 不承担任何表达，
     * 却每行都要一个离屏缓冲。
     *
     * 叠加边缘淡出（`EDGE_FADE_RATIO`）后，那几行本身还要再被蒙版
     * 擦掉一截，就更看不出来了。
     *
     * **实际取 3 而不是 8**：8 是「不丢任何可见层次」的上界，但真机上
     * 8 行 blur 仍然不够顺（Janky 7.6%、90 分位 12ms 但 95 分位 36ms，
     * 换行时仍有肉眼可见的卡顿）。成本正比于挂 blur 的行数，
     * 这是唯一有效的杠杆（离散半径、不做动画都试过，均无效甚至更差，
     * 见 [blurSteps]）。
     *
     * 取 3 的依据是**景深只在焦点区附近有意义**：当前行清晰、
     * 紧邻的三行渐次模糊，已经足够表达「这句在唱、下几句在后面」。
     * 再远的行 alpha 也低（第 4 行起 ≤0.445），本来就在视觉边缘。
     *
     * 设为 0 或负数表示不截断（全部挂 blur），供实验室对比用。
     */
    val blurCutoffLines: Int = 3,

    /**
     * 模糊半径离散成几档（含 0 那档）。**默认关闭（0 = 连续半径）。**
     *
     * 曾寄望它能提性能——想法是「同档的行共用同一个半径，Skia 可以
     * 复用 RenderEffect」。**真机实测否掉了**：开 3 档反而更差
     * （Janky 7.6% → 12.2%，90 分位 12ms → 25ms）。
     *
     * 两个原因：
     *
     * 1. Skia **不会因为半径相同就复用**。每个 `Modifier.blur` 的内容
     *    不同（不同的文字），即便半径一样也得各做一遍——离屏缓冲的
     *    数量一个没少，而那才是真正的成本。
     * 2. 向上取整把 offset=1 的半径从 0.9dp 抬到一整档（3dp），
     *    **半径越大高斯核越大、算得越慢**，反倒把成本推高了。
     *
     * 结论：成本正比于「挂了 blur 的行数」与「半径大小」，与半径是否
     * 离散无关。真正有效的杠杆是 [blurCutoffLines]（减少行数）
     * 和 [maxBlurDp]（减小半径）。
     *
     * 保留这个参数是为了让上面这条结论可复现——把它设回 3 就能重现
     * 那次退步，省得将来有人再想一遍同样的主意。
     */
    val blurSteps: Int = 0,

    /**
     * 模糊／透明度在当前行**上方**的跨度倍率。
     *
     * 1f 表示上下对称，即与前一版一致。小于 1 会让上方的行更快糊掉、
     * 淡出得更狠——考虑到焦点已压到第 3 行、上方只剩两行已唱过的内容，
     * 理论上可以更激进，但默认先保持对称：位移的梯度这次已经改成有向的，
     * 再同时把清晰度也改成有向，出了问题分不清是哪个变量在起作用。
     * 留给实验室去试。
     */
    val upperFadeScale: Float = 1f,

    /**
     * 非当前行的起始透明度，随距离线性衰减到 [alphaFar]。
     *
     * 这三个 alpha 参数现在**独自承担全部层次**（见 [uniformBlurDp]
     * 默认关闭）。早先它们是配合 blur 设计的，跨度刻意收得很窄
     * （0.55 起、地板 0.3），因为深浅主要交给模糊去表达；
     * 去掉模糊后必须把跨度拉开，否则各行会糊成一片分不出远近。
     *
     * 0.45 起步比早先低：当前行恒为 1.0，第一档拉开得越多，
     * 焦点越明确——这是纯 alpha 方案里建立焦点的唯一手段。
     */
    val alphaNear: Float = 0.45f,

    /** 最远处行的透明度地板。压得比早先（0.3）更低，把景深让给透明度。 */
    val alphaFar: Float = 0.12f,

    /** 透明度每远一行衰减的量。比早先（0.035）更陡，补上模糊让出的层次。 */
    val alphaStep: Float = 0.06f,

    /**
     * 淡入淡出（透明度、模糊）的过渡时长。
     *
     * 与 [focusLeadMs] 配着看：默认口径是**焦点先切、位移紧随其后**
     * （Apple Music 的时序），所以这一段要短、要干脆——它现在是换行时
     * 用户最先看到的变化。
     *
     * **必须明显短于 [focusLeadMs]**，否则高亮还没淡完位移就开始了，
     * 两件事在时间上重叠，观感就是「同时进行」——即便延迟本身完全生效。
     *
     * 这条栽过一次：延迟 90ms 而这里 260ms，真机逐帧量到
     * 「+98ms 排版切换、+165ms 开始移动、+278ms 透明度才到 1.0」，
     * 后一半的淡入与整段位移完全重叠。当时只盯着延迟有没有生效，
     * 而延迟是生效的（日志里分毫不差），问题在两段时长的**比例**上。
     * 所以调时序要同时看这两个值，只调一个必然找不到点。
     */
    val fadeAnimMs: Int = 140,

    /**
     * 焦点（透明度 + 模糊）相对位移的**时序偏移**，毫秒，**有符号**。
     *
     * - **正数**：焦点先切，隔这么久再开始位移。这是 Apple Music 的时序，
     *   也是现在的默认——观察真机上的 Apple Music，换行时是先高亮下一句，
     *   极短间隔后整列才开始滚动。
     * - **负数**：位移先走，绝对值就是焦点的等待时长。这是本项目早先的
     *   口径（曾写死为「fade 延迟 320ms」）。
     * - **0**：两件事同时开始。实测这个点观感最差——「一边往上滚一边对焦」，
     *   两个变化叠在一起显得急。这也是早先引入延迟的原因。
     *
     * 做成有符号的单参数而不是「把延迟从 fade 挪到位移」，是为了让实验室
     * 能**连续扫过**整个时序空间：这块栽过四次的教训就是「端点数字看着
     * 没问题、代码里也看不出问题」，只有连着对比才分得出来。
     * 两边各给一个独立延迟参数则有一半状态是冗余的（同时延迟 = 整体延后），
     * 反而更难找到点。
     *
     * 换算见 [focusDelayMs] / [scrollDelayMs]：谁落后谁延迟，另一边恒为 0。
     * 绝对值要**明显小于** [settleTweenMs]，让两段稍有交叠而不是完全排队——
     * 完全排队会有一个能察觉的停顿。
     *
     * 同时必须**大于 [fadeAnimMs]**，否则高亮还没淡完位移就开始了，
     * 用户看到的仍是「同时进行」。取 200ms：略大于 140ms 的淡入，
     * 中间留出约 60ms 的空档让「高亮已经切完、还没开始动」这个状态
     * 真的能被看见——这正是「先高亮、停一下、再移动」里那个「停一下」。
     */
    val focusLeadMs: Int = 200,
) {
    /** 焦点（alpha / blur）动画的起始延迟。焦点先行时为 0。 */
    val focusDelayMs: Int get() = if (focusLeadMs >= 0) 0 else -focusLeadMs

    /**
     * 位移的起始延迟。位移先行时为 0。
     *
     * **不是动画 spec 的 delayMillis**，而是 `LyricsScroller` 里排版行号
     * （layoutIndex）滞后于焦点行号的时长。早先确实是挂在 tween 的
     * delayMillis 上，但那样只在歌曲开头生效——窗口开始滑动后位移改由
     * shiftAnim 驱动，而它为了不让排版跳变裸露必须无延迟，于是焦点先行
     * 在真实播放的绝大部分时间里都是失效的。
     * 改成延迟排版本身之后，两条位移路径都自动跟着延后。
     */
    val scrollDelayMs: Int get() = if (focusLeadMs > 0) focusLeadMs else 0

    /**
     * 实际锚点行号：开了译文就**往上提一行**。
     *
     * [anchorRow] 是「行数」，而锚点位置是按各行**标称高度**累加出来的
     * （见 `LyricsOverlay` 的 anchorTopPx）。这两件事在不带译文时等价
     * （每行都是 52dp），开了译文就脱钩了——带译文的行标称高度约 82dp，
     * 同样的三行上文从 156dp 涨到 246dp，焦点凭空下沉 90dp（近两个行高），
     * 预读区被压掉一大截。
     *
     * 提一行之后 2×82=164dp，与不带译文的 3×52=156dp 几乎重合，
     * 焦点在屏幕上的位置基本不变。
     *
     * **不做成按高度比例的真·相对锚点**：那样上方的上下文行数会变成可变的
     * （2~4 行不等，取决于上方这几行恰好有几行带译文），且会随歌曲推进而变。
     * 焦点的像素位置是稳的，但上方行数会跳。固定行数的确定性更符合
     * [anchorRow] 一贯的口径——锚点只取决于数据、组合期就能算出来。
     *
     * 代价是这**不是严格的等高补偿**：译文行数普遍少于原文行数
     * （实测同一首歌 18/17、20/18、27/26），上方那两行不一定都带译文，
     * 所以焦点仍会在 156~164dp 之间小幅浮动。但浮动幅度远小于原先的 90dp。
     */
    fun anchorRowFor(translationEnabled: Boolean): Int =
        if (translationEnabled) (anchorRow - 1).coerceAtLeast(0) else anchorRow

    /**
     * 第 [screenRow] 行（0 基，0 为屏幕顶）的缓动「懒惰度」。
     *
     * 返回值直接当贝塞尔曲线第一个控制点的 x 用：越大起步越慢。
     * 因为 y 恒为 0、终点控制点固定，这条曲线**单调不减**，
     * 位移只会逼近目标，不会越过——即用户要的「趋近于 0」而非震荡。
     *
     * `screenRow` 可以是负数（目标位置在容器顶边之外的行），此时按 0 处理：
     * 那些行已经滑出裁切区，按最干脆档处理即可，没必要继续外推。
     */
    fun easeAt(screenRow: Int): Float = interpolate(screenRow, easeTop, easeBottom)

    /**
     * 整列统一上移用的缓动「懒惰度」。
     *
     * 恒为 [easeTop]，即最干脆的那一档——**可视区内所有行共用它**，
     * 于是整列作为一个刚体同速上移。
     *
     * 这是刻意去掉逐行错峰后的口径。早先每行按屏幕位置取不同的懒惰度
     * （上干脆、下懒），意图是 Apple Music 那种「上面的行先动、下面的行
     * 被拖着走」的链条感；但那条梯度让**每一行的起步都是慢的**
     * （懒惰度即贝塞尔第一个控制点的 x，越大起步越平），
     * 整列于是显得「先拱一下再走」，实测观感就是急。
     *
     * 现在改为：可视区统一走 [easeTop]（先快后慢的吸附感），
     * 错峰只保留在**即将进入可视区的那一行**上（见 [incomingEase]）——
     * 链条感集中到一处反而更清楚，也不拖泥带水。
     */
    val blockEase: Float get() = easeTop

    /**
     * 即将从下方进入可视区的那一行用的懒惰度，恒为 [easeBottom]。
     *
     * 它明显懒于整列（默认 0.95 对 0.1），表现为「最下面那句晚一拍、
     * 再缓缓吸附上来」。这是整套动画里**唯一**保留错峰的地方。
     *
     * 为什么只给这一行：它正从边缘淡出区里冒出来，本来就没有阅读价值，
     * 让它慢一点既不影响读，又能留住「整列被带着走」的层次。
     * 而可视区内的行一旦各自不同速，就会互相错开、显得散。
     */
    val incomingEase: Float get() = easeBottom

    /**
     * 这一行是不是「即将进入可视区」的那一行。
     *
     * [screenRow] 是动画结束后它会落在屏幕上的第几行，[visibleRows] 是
     * 容器能放下的行数。落在可视区之外（含最后一行的边缘淡出区）的行
     * 都按 incoming 处理——它们同样在往上飘，同样不该干扰阅读。
     */
    fun isIncoming(screenRow: Int, visibleRows: Int): Boolean =
        screenRow >= visibleRows

    /**
     * 这一行实际该用的懒惰度：可视区内统一 [blockEase]，
     * 下方待进入的行用 [incomingEase]。
     */
    fun easeFor(screenRow: Int, visibleRows: Int): Float =
        if (isIncoming(screenRow, visibleRows)) incomingEase else blockEase

    /**
     * 把屏幕行号映射到 [0,1]，再在 [top]、[bottom] 之间线性插值。
     *
     * 梯度**与 [anchorRow] 无关**：它描述的是「这行在屏幕上处于什么位置」，
     * 而不是「离当前行多远」。当前行只是恰好落在这条曲线的某一点上，
     * 挪动锚点会让它取到不同的快慢，但不会改变整条曲线本身。
     *
     * 早先这里把跨度写成 `anchorRow + gradientRampLines`、让曲线在锚点处
     * 分两段，是残留的「以当前行为中心」的思路——梯度一旦改成纯粹的
     * 屏幕位置函数，锚点就不该出现在这个式子里。
     */
    private fun interpolate(screenRow: Int, top: Float, bottom: Float): Float {
        if (gradientRampLines <= 0f) return bottom
        val t = (screenRow.toFloat() / gradientRampLines).coerceIn(0f, 1f)
        return top + (bottom - top) * t
    }

    /**
     * 距当前行 [offset] 行处的模糊半径（dp）。[offset] 为负表示在当前行上方。
     *
     * 当前行恒为 0：它是阅读焦点，任何模糊都是倒扣分。
     *
     * 超出 [blurCutoffLines] 的行也返回 0，**这是性能优化而非观感选择**：
     * 渲染侧对半径 0 的行不挂 `Modifier.blur`，于是省掉一个全屏宽的
     * 离屏缓冲。那个距离上 alpha 早已撞到 [alphaFar] 的地板、blur 也
     * 接近封顶，各行之间本来就没有层次差别（详见 [blurCutoffLines]）。
     */
    fun blurDpAt(offset: Int): Float {
        // 两档模型（默认）：当前行一档，其余**全部同一档**，与距离无关。
        // 照着 Android 版 Apple Music 做的，同时也是流畅度的关键——
        // 十几种互不相同的半径改成一种，Skia 才谈得上复用。
        // 详见 uniformBlurDp。
        if (uniformBlurDp >= 0f) {
            if (offset == 0) return currentBlurDp
            // 超出截断距离的行**完全不挂 blur**，层次纯靠 alpha 承担。
            // 这才是省离屏缓冲的地方：统一半径只是让 Skia 有复用的余地，
            // 但每一行仍各要一个缓冲；只有不挂，缓冲才真的消失。
            if (blurCutoffLines > 0 && kotlin.math.abs(offset) > blurCutoffLines) return 0f
            return uniformBlurDp
        }

        // 以下是逐行渐进的旧模型，仅在 uniformBlurDp 为负时启用（实验室对比用）
        if (offset == 0) return 0f
        if (blurCutoffLines > 0 && kotlin.math.abs(offset) > blurCutoffLines) return 0f
        val ramp = if (offset < 0) blurRampLines * upperFadeScale else blurRampLines
        val raw = if (ramp <= 0f) {
            maxBlurDp
        } else {
            maxBlurDp * (kotlin.math.abs(offset) / ramp).coerceIn(0f, 1f)
        }
        return snapBlur(raw)
    }

    /**
     * 把连续半径吸附到 [blurSteps] 个档位上。见该字段的说明。
     *
     * 向上取整而非四舍五入：宁可略糊也不要让本该有模糊的行落到 0 档——
     * 那会让紧邻当前行的行突然变清晰，焦点区的层次就断了。
     */
    private fun snapBlur(raw: Float): Float {
        if (blurSteps <= 0 || maxBlurDp <= 0f) return raw
        if (raw <= 0f) return 0f
        val stepSize = maxBlurDp / blurSteps
        val tier = kotlin.math.ceil(raw / stepSize).toInt().coerceIn(1, blurSteps)
        return stepSize * tier
    }

    /** 距当前行 [offset] 行处的透明度。[isCurrent] 单独传：前奏期没有当前行。 */
    fun alphaAt(offset: Int, isCurrent: Boolean): Float {
        if (isCurrent) return 1f
        val distance = kotlin.math.abs(offset)
        val step = if (offset < 0 && upperFadeScale > 0f) alphaStep / upperFadeScale else alphaStep
        return (alphaNear - (distance - 1) * step).coerceIn(alphaFar, 1f)
    }

    companion object {
        /** 真机调出来的一组值，release 包恒用这套。 */
        val DEFAULT = LyricsAnimSpec()
    }
}
